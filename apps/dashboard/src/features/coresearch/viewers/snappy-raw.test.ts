import { describe, expect, it } from 'vitest';
import { decompressSnappyRaw } from './snappy-raw';
describe('raw Snappy decompression', () => {
  it('decodes literals and overlapping one-byte copies', () => {
    // Raw block for "abcabcabcabc": 12 output bytes, literal abc, copy 9 from offset 3.
    expect(
      new TextDecoder().decode(
        decompressSnappyRaw(Uint8Array.from([12, 8, 97, 98, 99, 21, 3]), 12, 100),
      ),
    ).toBe('abcabcabcabc');
  });
  it('supports two- and four-byte copy offsets', () => {
    expect(
      new TextDecoder().decode(
        decompressSnappyRaw(Uint8Array.from([8, 12, 97, 98, 99, 100, 14, 4, 0]), 8, 100),
      ),
    ).toBe('abcdabcd');
    expect(
      new TextDecoder().decode(
        decompressSnappyRaw(Uint8Array.from([8, 12, 97, 98, 99, 100, 15, 4, 0, 0, 0]), 8, 100),
      ),
    ).toBe('abcdabcd');
  });
  it('rejects bad sizes, invalid offsets, truncated data, trailing data and bombs', () => {
    for (const bytes of [
      [1, 0],
      [4, 1, 0],
      [1, 0, 65, 0],
      [255, 255, 255, 255, 15],
    ])
      expect(decompressSnappyRaw(Uint8Array.from(bytes), 1, 100)).toBeUndefined();
    expect(decompressSnappyRaw(Uint8Array.from([4, 12, 97, 98, 99, 100]), 3, 100)).toBeUndefined();
    expect(decompressSnappyRaw(Uint8Array.from([4, 12, 97, 98, 99, 100]), 4, 3)).toBeUndefined();
  });
});

it('decodes a vector independently generated by snappyjs 0.7.0', () => {
  const encoded =
    'rBGQUGFycXVldCBkYXRhIHBhZ2U6IGFscGhhIGJldGEgZ2FtbWEuIP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAP4lAA0l';
  const input = Uint8Array.from(atob(encoded), (c) => c.charCodeAt(0));
  const expected = 'Parquet data page: alpha beta gamma. '.repeat(60);
  expect(new TextDecoder().decode(decompressSnappyRaw(input, expected.length, 4096))).toBe(
    expected,
  );
});
