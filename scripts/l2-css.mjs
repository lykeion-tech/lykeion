// Split selector lists without splitting commas inside :is(), :where() or attributes.
function selectors(value) {
  const result = [];
  let depth = 0;
  let start = 0;
  let quote = '';
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (value[i - 1] === '\\') continue;
    if (quote) {
      if (c === quote) quote = '';
      continue;
    }
    if (c === '"' || c === "'") {
      quote = c;
      continue;
    }
    if (c === '(' || c === '[') depth++;
    if (c === ')' || c === ']') depth--;
    if (c === ',' && depth === 0) {
      result.push(value.slice(start, i).trim());
      start = i + 1;
    }
  }
  result.push(value.slice(start).trim());
  return result;
}
function scope(css) {
  const tree = postcss.parse(css);
  tree.walkRules((rule) => {
    // Nested selectors already inherit the outer scope. Animation stops do not.
    for (let p = rule.parent; p; p = p.parent) {
      if (p.type === 'rule' || (p.type === 'atrule' && /keyframes$/.test(p.name))) return;
    }
    const scoped = selectors(rule.selector).flatMap((s) => {
      if (/\[data-theme=["'](?:dawn|pale|barbie)["']\]/.test(s)) return [];
      if (/^\[data-theme=["']midnight["']\]$/.test(s))
        return [':root[data-theme="dark"] .coresearch'];
      if (/^\[data-theme=["']ash["']\]$/.test(s))
        return [':root:not([data-theme="dark"]) .coresearch'];
      if (/^(?::root|:host|html|body|#root)$/.test(s)) return ['.coresearch'];
      if (/^html\b/.test(s)) return [s.replace(/^html\b/, '.coresearch')];
      if (s === '*') return ['.coresearch', '.coresearch *'];
      return /^[.:#[]/.test(s) ? [`.coresearch${s}`, `.coresearch ${s}`] : [`.coresearch ${s}`];
    });
    if (scoped.length) rule.selector = [...new Set(scoped)].join(', ');
    else rule.remove();
  });
  // Flatten the source cascade in its declared order: host styles are
  // unlayered, so leaving the port layered would let the host reset win.
  // Source unlayered component rules retain their highest precedence.
  const buckets = new Map(
    ['properties', 'theme', 'base', 'components', 'utilities'].map((n) => [n, []]),
  );
  tree.walkAtRules('layer', (rule) => {
    if (rule.nodes) {
      const bucket = buckets.get(rule.params) ?? [];
      bucket.push(...rule.nodes.map((n) => n.clone()));
      buckets.set(rule.params, bucket);
    }
    rule.remove();
  });
  const flat = postcss.root();
  for (const nodes of buckets.values()) flat.append(nodes);
  flat.append(tree.nodes);
  // The host sets html to 14px; L2 uses the browser default 16px.
  // Resolve source rem lengths locally without changing the surrounding shell.
  flat.walkDecls((decl) => {
    decl.value = decl.value.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `${Number(n) * 16}px`);
  });
  return flat.toString();
}
