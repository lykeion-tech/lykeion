// patterned yields n bytes of text without holding them in memory.
type patterned struct{ left int64 }

func (p *patterned) Read(b []byte) (int, error) {
	if p.left <= 0 {
		return 0, io.EOF
	}
	if int64(len(b)) > p.left {
		b = b[:p.left]
	}
	for i := range b {
		b[i] = 'a' + byte(i%26)
	}
	p.left -= int64(len(b))
	return len(b), nil
}

// upload posts one file of n generated bytes as a multipart body, streamed.
func (s *server) upload(t *testing.T, tok, wsID, name string, n int64) (int, map[string]any) {
	t.Helper()
	pr, pw := io.Pipe()
	mw := multipart.NewWriter(pw)
	go func() {
		part, err := mw.CreateFormFile("file", name)
		if err == nil {
			_, err = io.Copy(part, &patterned{left: n})
		}
		if err == nil {
			err = mw.Close()
		}
		pw.CloseWithError(err)
	}()
	req, _ := http.NewRequest("POST", s.URL+"/api/attachments", pr)
	req.Header.Set("Content-Type", mw.FormDataContentType())
	req.Header.Set("Authorization", "Bearer "+tok)
	req.Header.Set("X-Workspace-ID", wsID)
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("upload: %v", err)
	}
	defer resp.Body.Close()
	var out map[string]any
	_ = json.NewDecoder(resp.Body).Decode(&out)
	return resp.StatusCode, out
}

func (s *server) attachmentCount(t *testing.T) int {
	var n int
	if err := s.Env.Owner.QueryRow(t.Context(), `SELECT count(*) FROM attachment`).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func TestAnUploadStreamsAndIsBounded(t *testing.T) {
	s := newServer(t)
	tok := s.signIn(t, "a@lab.org")
	w := s.workspace(t, tok, "up-lab")
	dir := s.H.Blobs.(storage.Local).Dir

	var before, after runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&before)
	code, out := s.upload(t, tok, w.ID, "big.txt", MaxAttachmentBytes+1)
	runtime.ReadMemStats(&after)
	if code != 413 {
		t.Fatalf("over the limit: %d %v", code, out)
	}
	if out["error"] != "A file can be at most 100 MB" {
		t.Fatalf("message: %v", out)
	}
	// Buffering the body would allocate at least its size.
	if grown := after.TotalAlloc - before.TotalAlloc; grown > 60<<20 {
		t.Fatalf("handler allocated %d MB for a 100 MB upload", grown>>20)
	}
	if n := s.attachmentCount(t); n != 0 {
		t.Fatalf("%d rows after a refused upload", n)
	}
	var blobs int
	var walk func(string)
	walk = func(d string) {
		es, _ := os.ReadDir(d)
		for _, e := range es {
			if e.IsDir() {
				walk(d + "/" + e.Name())
			} else {
				blobs++
			}
		}
	}
	walk(dir)
	if blobs != 0 {
		t.Fatalf("%d blobs after a refused upload", blobs)
	}

	const size = 5 << 20
	code, out = s.upload(t, tok, w.ID, "notes.csv", size)
	if code != 201 {
		t.Fatalf("5 MB upload: %d %v", code, out)
	}
	h := sha256.New()
	_, _ = io.Copy(h, &patterned{left: size})
	want := hex.EncodeToString(h.Sum(nil))
	if out["sha256"] != want || out["size_bytes"] != float64(size) || out["name"] != "notes.csv" || out["content_type"] != "text/csv" {
		t.Fatalf("response %v", out)
	}
	var key, sum string
	var card *uuid.UUID
	if err := s.Env.Owner.QueryRow(t.Context(), `SELECT blob_key, sha256, card_id FROM attachment WHERE id=$1`, out["id"]).Scan(&key, &sum, &card); err != nil {
		t.Fatal(err)
	}
	if sum != want || card != nil || key != w.ID+"/attachments/"+out["id"].(string) {
		t.Fatalf("row %s %s %v", key, sum, card)
	}
	rc, err := s.H.Blobs.Get(t.Context(), key)
	if err != nil {
		t.Fatal(err)
	}
	defer rc.Close()
	hb := sha256.New()
	if n, _ := io.Copy(hb, rc); n != size || hex.EncodeToString(hb.Sum(nil)) != want {
		t.Fatalf("blob holds %d bytes", n)
	}
}

func TestAnAcceptedTextUploadIsNotHeldInMemory(t *testing.T) {
	s := newServer(t)
	tok := s.signIn(t, "a@lab.org")
	w := s.workspace(t, tok, "up-lab")
	var before, after runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&before)
	code, out := s.upload(t, tok, w.ID, "big.txt", MaxAttachmentBytes)
	runtime.ReadMemStats(&after)
	if code != 201 {
		t.Fatalf("100 MB upload: %d %v", code, out)
	}
	// Reading the file's text whole would allocate at least its size.
	if grown := after.TotalAlloc - before.TotalAlloc; grown > 60<<20 {
		t.Fatalf("handler allocated %d MB for a 100 MB text upload", grown>>20)
	}
	var textSum string
	if err := s.Env.Owner.QueryRow(t.Context(), `SELECT text_sha256 FROM attachment WHERE id=$1`, out["id"]).Scan(&textSum); err != nil {
		t.Fatal(err)
	}
	if textSum != out["sha256"] {
		t.Fatalf("the file's text was not kept: text sha256 %q, file %v", textSum, out["sha256"])
	}
}

