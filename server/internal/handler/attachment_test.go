func TestTheSweepRemovesOnlyStalePendingUploads(t *testing.T) {
	s := newServer(t)
	tok := s.signIn(t, "a@lab.org")
	w := s.workspace(t, tok, "up-lab")
	linked := s.idleCard(t, tok, w.ID, "A question?")
	ids := map[string]string{}
	for _, name := range []string{"old", "fresh", "linked"} {
		_, out := s.upload(t, tok, w.ID, name+".txt", 100)
		ids[name] = out["id"].(string)
	}
	exec := func(q string, args ...any) {
		if _, err := s.Env.Owner.Exec(t.Context(), q, args...); err != nil {
			t.Fatal(err)
		}
	}
	exec(`UPDATE attachment SET created_at = now() - interval '25 hours' WHERE id = $1 OR id = $2`, ids["old"], ids["linked"])
	exec(`UPDATE attachment SET created_at = now() - interval '1 hour' WHERE id = $1`, ids["fresh"])
	exec(`UPDATE attachment SET card_id = $2 WHERE id = $1`, ids["linked"], linked.ID)

	if err := SweepAttachments(t.Context(), s.H.Store, s.H.Blobs, time.Now); err != nil {
		t.Fatal(err)
	}
	exists := func(name string) (rows bool, blob bool) {
		var n int
		_ = s.Env.Owner.QueryRow(t.Context(), `SELECT count(*) FROM attachment WHERE id=$1`, ids[name]).Scan(&n)
		rc, err := s.H.Blobs.Get(t.Context(), w.ID+"/attachments/"+ids[name])
		if err == nil {
			rc.Close()
		}
		// the text read at upload goes with the file
		tc, terr := s.H.Blobs.Get(t.Context(), records.TextKey(w.ID+"/attachments/"+ids[name]))
		if terr == nil {
			tc.Close()
		}
		if (err == nil) != (terr == nil) {
			t.Fatalf("%s: blob %v, text %v", name, err, terr)
		}
		return n == 1, err == nil
	}
	for name, want := range map[string]bool{"old": false, "fresh": true, "linked": true} {
		if r, b := exists(name); r != want || b != want {
			t.Fatalf("%s: row %v blob %v, want %v", name, r, b, want)
		}
	}
}

