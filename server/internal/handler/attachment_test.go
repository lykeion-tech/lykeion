func TestAnUploadMayBeFiveGigabytes(t *testing.T) {
	s := newServer(t)
	tok := s.signIn(t, "a@lab.org")
	w := s.workspace(t, tok, "up-lab")
	dir := s.H.Blobs.(storage.Local).Dir

	var before, after runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&before)
	code, out := s.upload(t, tok, w.ID, "big.txt", (5<<30)+1)
	runtime.ReadMemStats(&after)
	if code != 413 {
		t.Fatalf("over the limit: %d %v", code, out)
	}
	if out["error"] != "A file can be at most 5 GB" {
		t.Fatalf("message: %v", out)
	}
	// Buffering the body would allocate at least its size.
	if grown := after.TotalAlloc - before.TotalAlloc; grown > 60<<20 {
		t.Fatalf("handler allocated %d MB for a 5 GB upload", grown>>20)
	}
	if n := s.attachmentCount(t); n != 0 {
		t.Fatalf("%d rows after a refused upload", n)
	}
	var blobs int
	var walk func(string)
	walk = func(d string) {
		es, _ := os.ReadDir(d)
		for _, e := range es {
			if e.IsDir() {
				walk(d + "/" + e.Name())
			} else {
				blobs++
			}
		}
	}
	walk(dir)
	if blobs != 0 {
		t.Fatalf("%d blobs after a refused upload", blobs)
	}

	const size = 5 << 20
	code, out = s.upload(t, tok, w.ID, "notes.csv", size)
	if code != 201 {
		t.Fatalf("5 MB upload: %d %v", code, out)
	}
	h := sha256.New()
	_, _ = io.Copy(h, &patterned{left: size})
	want := hex.EncodeToString(h.Sum(nil))
	if out["sha256"] != want || out["size_bytes"] != float64(size) || out["name"] != "notes.csv" || out["content_type"] != "text/csv" {
		t.Fatalf("response %v", out)
	}
	var key, sum string
	var card *uuid.UUID
	if err := s.Env.Owner.QueryRow(t.Context(), `SELECT blob_key, sha256, card_id FROM attachment WHERE id=$1`, out["id"]).Scan(&key, &sum, &card); err != nil {
		t.Fatal(err)
	}
	if sum != want || card != nil || key != w.ID+"/attachments/"+out["id"].(string) {
		t.Fatalf("row %s %s %v", key, sum, card)
	}
	rc, err := s.H.Blobs.Get(t.Context(), key)
	if err != nil {
		t.Fatal(err)
	}
	defer rc.Close()
	hb := sha256.New()
	if n, _ := io.Copy(hb, rc); n != size || hex.EncodeToString(hb.Sum(nil)) != want {
		t.Fatalf("blob holds %d bytes", n)
	}
}

